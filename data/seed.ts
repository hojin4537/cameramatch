// Script to upload seed data to Firestore
export async function uploadSeedData() {
  const { collection, addDoc, getFirestore } = await import("firebase/firestore");
  const { initializeApp, getApps } = await import("firebase/app");

  // Firebase 초기화 (스크립트 실행 시 환경 변수가 이미 로드되어 있어야 함)
  const firebaseConfig = {
    apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY,
    authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
    projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
    storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET,
    messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID,
    appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID,
  };

  if (!firebaseConfig.apiKey || !firebaseConfig.projectId) {
    throw new Error(
      "Firebase 환경 변수가 설정되지 않았습니다. .env.local 파일을 확인해주세요."
    );
  }

  let app;
  if (getApps().length === 0) {
    app = initializeApp(firebaseConfig);
  } else {
    app = getApps()[0];
  }

  const db = getFirestore(app);

  // db가 제대로 초기화되었는지 확인
  if (!db) {
    throw new Error(
      "Firebase db가 초기화되지 않았습니다. 환경 변수를 확인해주세요."
    );
  }

  console.log("Uploading cameras...");
  for (const camera of seedCameras) {
    await addDoc(collection(db, "cameras"), camera);
    console.log(`Uploaded: ${camera.brand} ${camera.model}`);
  }

  console.log("Uploading lenses...");
  for (const lens of seedLenses) {
    await addDoc(collection(db, "lenses"), lens);
    console.log(`Uploaded: ${lens.brand} ${lens.model}`);
  }

  console.log("Seed data upload complete!");
}
